const { _electron: electron } = require('/Users/zyc/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const path = require('node:path')
const fs = require('node:fs')
const os = require('node:os')

const root = path.resolve(__dirname, '..')
const outputDir = path.join(root, 'output', 'playwright', 'watch-skill')
const videoPath = path.join(root, '.tools', 'watch-skill-smoke.mp4')
fs.mkdirSync(outputDir, { recursive: true })

;(async () => {
  const executablePath = path.join(root, 'node_modules', 'electron', 'dist', 'Electron.app', 'Contents', 'MacOS', 'Electron')
  const userDataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'watch-skill-ui-'))
  const app = await electron.launch({ executablePath, args: ['.', `--user-data-dir=${userDataDir}`], cwd: root, env: { ...process.env, ELECTRON_RUN_AS_NODE: '', NODE_OPTIONS: '' } })
  try {
    const page = await app.firstWindow()
    await page.waitForLoadState('domcontentloaded')
    const profile = { id:'watch-skill-qa',email:'qa@example.test',name:'Watch Skill 验收',isOwner:true,status:'ACTIVE',mustChangePassword:false,lastLoginAt:null,org:{id:'qa-org',name:'验收组织'},roles:[],permissions:'ALL',stores:null }
    await page.route('**/api/auth/me', route => route.fulfill({ status:200, contentType:'application/json', body:JSON.stringify(profile) }))
    await page.evaluate(value => {
      localStorage.setItem('sourcing.auth.tokens:v1',JSON.stringify({accessToken:'qa',refreshToken:'qa',refreshTokenExpiresAt:'2099-01-01T00:00:00.000Z'}))
      localStorage.setItem('sourcing.auth.profile:v1',JSON.stringify(value))
    }, profile)
    await page.reload()
    await page.waitForTimeout(1200)
    await page.getByRole('button',{name:'AI视频'}).click()
    await page.getByText('Watch Skill',{exact:true}).click()
    await page.getByRole('heading',{name:'Watch Skill｜视频解析'}).waitFor()
    await page.waitForFunction(() => document.querySelector('.watch-skill-title em')?.textContent === '可用')
    const checks = await page.locator('.watch-skill-checks').innerText()
    for (const expected of ['✓ 解析引擎','✓ FFmpeg','✓ Whisper','✓ OCR']) if (!checks.includes(expected)) throw new Error(`环境状态缺少：${expected}；实际=${checks}`)
    const youtubeInput=page.getByLabel('YouTube 链接'),downloadButton=page.getByRole('button',{name:'下载并解析'})
    if(!(await downloadButton.isDisabled()))throw new Error('YouTube 链接为空时下载按钮应禁用')
    await youtubeInput.fill('https://example.com/video');await downloadButton.click();await page.getByText('请输入 YouTube HTTPS 链接').waitFor();await youtubeInput.fill('')
    await page.screenshot({path:path.join(outputDir,'01-ready.png'),fullPage:true})

    const task = await page.evaluate(async source => window.desktop.system.watchSkillAnalyze(source), videoPath)
    if (task.status !== 'COMPLETED') throw new Error(`解析状态错误：${task.status}`)
    if (!task.report.includes('Duration:')) throw new Error('解析报告缺少时长')
    if (!task.framePaths.length) throw new Error('未生成关键帧')
    await page.getByRole('button',{name:'重新检查'}).click()
    await page.waitForFunction(() => document.querySelectorAll('.watch-skill-history button').length > 0)
    await page.waitForFunction(() => [...document.images].some(image => image.alt === '视频关键帧' && image.complete && image.naturalWidth > 0))
    if (!(await page.getByText('watch-skill-smoke.mp4',{exact:true}).count())) throw new Error('历史记录未显示测试视频')
    if (!(await page.getByText(/张关键帧/).count())) throw new Error('结果区未显示关键帧数量')
    await page.screenshot({path:path.join(outputDir,'02-result.png'),fullPage:true})

    await page.reload()
    await page.waitForTimeout(1000)
    await page.getByRole('button',{name:'AI视频'}).click()
    await page.getByText('Watch Skill',{exact:true}).click()
    await page.locator('.watch-skill-history button').filter({hasText:'watch-skill-smoke.mp4'}).first().waitFor()
    await page.screenshot({path:path.join(outputDir,'03-persisted.png'),fullPage:true})
    const assets = await page.evaluate(() => [...document.querySelectorAll('link[rel="stylesheet"],script[src]')].map(node => node.getAttribute('href') || node.getAttribute('src')).filter(Boolean))
    console.log(JSON.stringify({passed:true,checks,taskId:task.id,frameCount:task.framePaths.length,persisted:true,assets,screenshots:['01-ready.png','02-result.png','03-persisted.png'].map(name=>path.join(outputDir,name))},null,2))
  } finally { await app.close() }
})().catch(error => { console.error('VERIFY FAILED:',error.stack||error.message); process.exit(1) })
