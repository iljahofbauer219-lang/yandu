const { _electron: electron } = require('/Users/zyc/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')

const root = path.resolve(__dirname, '..')
const output = path.join(root, 'output/playwright/resource2skill/imported-skill.png')
const formalUserData = path.join(os.homedir(), 'Library/Application Support/cross-border-sourcing-desktop')
;(async () => {
  const userDataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'resource2skill-import-qa-'))
  fs.copyFileSync(path.join(formalUserData, 'resource2skill-library.json'), path.join(userDataDir, 'resource2skill-library.json'))
  fs.copyFileSync(path.join(formalUserData, 'watch-skill-tasks.json'), path.join(userDataDir, 'watch-skill-tasks.json'))
  fs.copyFileSync(path.join(formalUserData, 'resource2skill-settings.json'), path.join(userDataDir, 'resource2skill-settings.json'))
  const executablePath = path.join(root, 'node_modules/electron/dist/Electron.app/Contents/MacOS/Electron')
  const app = await electron.launch({ executablePath, args: ['.', `--user-data-dir=${userDataDir}`], cwd: root, env: { ...process.env, ELECTRON_RUN_AS_NODE: '', NODE_OPTIONS: '' } })
  try {
    const page = await app.firstWindow()
    const profile = { id:'r2s-import-qa', email:'qa@example.test', name:'R2S验收', isOwner:true, status:'ACTIVE', mustChangePassword:false, lastLoginAt:null, org:{id:'qa',name:'验收'}, roles:[], permissions:'ALL', stores:null }
    await page.route('**/api/auth/me', route => route.fulfill({ status:200, contentType:'application/json', body:JSON.stringify(profile) }))
    await page.evaluate(value => { localStorage.setItem('sourcing.auth.tokens:v1', JSON.stringify({accessToken:'qa',refreshToken:'qa',refreshTokenExpiresAt:'2099-01-01T00:00:00.000Z'})); localStorage.setItem('sourcing.auth.profile:v1', JSON.stringify(value)) }, profile)
    await page.reload(); await page.waitForTimeout(900)
    await page.getByRole('button', { name:'AI视频' }).click()
    await page.getByText('Watch Skill', { exact:true }).click()
    const downloadButton=page.getByRole('button',{name:'下载并解析'})
    if(!(await downloadButton.isDisabled()))throw new Error('YouTube 链接为空时下载按钮应禁用')
    const watchHistory = page.locator('.watch-skill-history button').filter({ hasText:'sKFhK0z1aCw.mp4' })
    await watchHistory.waitFor()
    const reportText = await page.locator('.watch-skill-result pre').textContent()
    if (!reportText?.includes('[29:07]')||!reportText.includes('## Frame OCR')) throw new Error('Watch Skill 页未载入完整 small 报告与 OCR')
    await page.getByRole('button', { name:'返回 AI视频' }).click()
    await page.getByText('Resource2Skill', { exact:true }).click()
    const sourceSelect = page.getByLabel('Watch Skill来源')
    await sourceSelect.waitFor()
    await page.waitForFunction(() => document.querySelectorAll('select[aria-label="Watch Skill来源"] option').length > 1)
    const sourceOptions = await sourceSelect.locator('option').allTextContents()
    if (!sourceOptions.some(text => text.includes('sKFhK0z1aCw.mp4'))) throw new Error(`Resource2Skill 来源中未显示 Watch 记录: ${JSON.stringify(sourceOptions)}`)
    await sourceSelect.selectOption({label:sourceOptions.find(text=>text.includes('sKFhK0z1aCw.mp4'))})
    await page.getByLabel('Resource2Skill领域').selectOption('general')
    const distillButton=page.getByRole('button',{name:'Gemini 蒸馏'})
    if(await distillButton.isDisabled())throw new Error('Key 与 Watch 来源已就绪时 Gemini 蒸馏按钮不应禁用')
    await distillButton.focus()
    await distillButton.press('Enter')
    try{await page.getByText('Gemini 蒸馏完成，已加入内部 Skill 库').waitFor({timeout:120000})}catch{throw new Error(`Gemini 蒸馏未完成: ${await page.locator('.resource2skill-source p').textContent()}`)}
    const generated=await page.getByLabel('SKILL.md内容').inputValue()
    if(!generated.includes('resource2skill_domain: general'))throw new Error('蒸馏结果未使用 general 领域')
    if((generated.match(/\[[0-9]{2}:[0-9]{2}\]/g)||[]).length<5)throw new Error('蒸馏结果未通过时间戳门禁')
    await page.reload();await page.waitForTimeout(900)
    await page.getByRole('button',{name:'AI视频'}).click();await page.getByText('Resource2Skill',{exact:true}).click()
    await page.getByText('sKFhK0z1aCw-distilled-skill',{exact:true}).waitFor()
    const content = await page.getByLabel('SKILL.md内容').inputValue()
    if(!content.includes('resource2skill_domain: general'))throw new Error('刷新后 general 蒸馏结果未持久化')
    if((content.match(/\[[0-9]{2}:[0-9]{2}\]/g)||[]).length<5)throw new Error('刷新后来源时间戳不足')
    fs.mkdirSync(path.dirname(output), { recursive:true })
    await page.screenshot({ path:output, fullPage:true, timeout:60000 })
    console.log(JSON.stringify({ passed:true, watchHistoryVisible:true, sourceSelectable:true, realApiDistill:true, qualityGatePassed:true, persistedAfterReload:true, editable:true, timestampCount:(content.match(/\[[0-9]{2}:[0-9]{2}\]/g)||[]).length, screenshot:output }, null, 2))
  } finally { await app.close() }
})().catch(error => { console.error(`VERIFY IMPORT FAILED: ${error.stack || error.message}`); process.exit(1) })
