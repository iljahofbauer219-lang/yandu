// 登录页服务器地址下拉选择验收：选项/回显/持久化/自定义兼容
const { _electron: electron } = require('/Users/zyc/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const path = require('node:path'), fs = require('node:fs'), os = require('node:os')
;(async () => {
  const executablePath = path.resolve(__dirname, '../node_modules/electron/dist/Electron.app/Contents/MacOS/Electron')
  const userDataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'yandu-serversel-'))
  const app = await electron.launch({ executablePath, args: ['--user-data-dir=' + userDataDir, '.'], cwd: path.resolve(__dirname, '..') })
  const page = await app.firstWindow()
  await page.waitForLoadState('domcontentloaded')
  await page.waitForSelector('.auth-server-toggle', { timeout: 20000 })

  console.log('TOGGLE_DEFAULT=' + (await page.textContent('.auth-server-toggle')).trim())
  await page.click('.auth-server-toggle')
  await page.waitForSelector('.auth-server-select select')
  const options = await page.$$eval('.auth-server-select select option', els => els.map(e => e.textContent + '=>' + e.value))
  console.log('OPTIONS=' + JSON.stringify(options))
  console.log('SELECTED=' + await page.$eval('.auth-server-select select', el => el.value))
  await page.screenshot({ path: path.resolve(__dirname, '53-server-select.png') })

  await page.selectOption('.auth-server-select select', 'http://127.0.0.1:8787')
  await page.waitForTimeout(200)
  console.log('TOGGLE_AFTER_SELECT=' + (await page.textContent('.auth-server-toggle')).trim())
  await page.screenshot({ path: path.resolve(__dirname, '54-server-select-local.png') })

  await page.evaluate(() => localStorage.setItem('sourcing.server-url:v1', 'http://192.168.1.50:8787'))
  await page.reload()
  await page.waitForSelector('.auth-server-toggle')
  await page.click('.auth-server-toggle')
  await page.waitForSelector('.auth-server-select select')
  const customOptions = await page.$$eval('.auth-server-select select option', els => els.map(e => e.textContent))
  console.log('CUSTOM_OPTIONS=' + JSON.stringify(customOptions))
  console.log('CUSTOM_SELECTED=' + await page.$eval('.auth-server-select select', el => el.value))
  await page.screenshot({ path: path.resolve(__dirname, '55-server-select-custom.png') })

  await app.close()
  process.exit(0)
})().catch(e => { console.error('ERR', e.message); process.exit(1) })
