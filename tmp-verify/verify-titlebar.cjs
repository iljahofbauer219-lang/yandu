  await page.click('.app-titlebar-actions button[title="主题"]')
  await page.waitForSelector('.titlebar-theme-menu')
  const menuItems = await page.$$eval('.titlebar-theme-menu button', els => els.map(e => e.textContent.trim().replace(/\s+/g, '')))
  console.log('MENU=' + JSON.stringify(menuItems))
  await page.screenshot({ path: path.resolve(__dirname, '49-theme-menu.png') })
  await page.click('.titlebar-theme-menu button:has-text("深色")')
  await page.waitForTimeout(400)
  console.log('DARK_ATTR=' + await page.evaluate(() => document.documentElement.dataset.theme || 'none'))
  await page.screenshot({ path: path.resolve(__dirname, '50-titlebar-dark.png') })
